export function getTechnologiesForRole(role: Role) {
  return TECHNOLOGIES.filter((t) => t.roles.includes(role));
}

export function filterQuestions(
  role: Role,
  level: Level,
  technologies: Technology[],
  categories: string[]
): Question[] {
  return QUESTIONS.filter(
    (q) =>
      q.role === role &&
      LEVEL_ORDER[q.level] <= LEVEL_ORDER[level] &&
      q.technologies.some((t) => technologies.includes(t)) &&
      categories.includes(q.category)
  );
}
